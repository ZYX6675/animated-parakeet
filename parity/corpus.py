"""Tiny synthetic sample files for testing the harness itself.

These are NOT real-world documents and are not guaranteed to open in Word, Excel, PowerPoint or
Photoshop. A real parity run needs a real corpus (public, donated, or generated by the original apps).
"""
from __future__ import annotations

import struct
import zipfile
from pathlib import Path
from xml.sax.saxutils import escape

CT = ('<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
      '<Default Extension="xml" ContentType="application/xml"/></Types>')
RELS = ('<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"/>')
WNS = 'xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"'
SNS = 'xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"'
PNS = 'xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"'


def _zip(path: Path, files: dict):
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", CT)
        z.writestr("_rels/.rels", RELS)
        for name, body in files.items():
            z.writestr(name, body)


def make_docx(path, paragraphs, table=False, styles=("Normal", "Heading1")):
    paras = "".join(f"<w:p><w:r><w:t>{escape(t)}</w:t></w:r></w:p>" for t in paragraphs)
    tbl = "<w:tbl><w:tr><w:tc><w:p><w:r><w:t>cell</w:t></w:r></w:p></w:tc></w:tr></w:tbl>" if table else ""
    doc = f'<?xml version="1.0" encoding="UTF-8"?><w:document {WNS}><w:body>{paras}{tbl}</w:body></w:document>'
    sty = f'<?xml version="1.0" encoding="UTF-8"?><w:styles {WNS}>' + "".join(
        f'<w:style w:type="paragraph" w:styleId="{s}"/>' for s in styles) + "</w:styles>"
    _zip(Path(path), {"word/document.xml": doc, "word/styles.xml": sty})


def make_xlsx(path, sheets=("Data",), strings=("Hello", "World")):
    wb = f'<?xml version="1.0"?><workbook {SNS}><sheets>' + "".join(
        f'<sheet name="{escape(n)}" sheetId="{i}"/>' for i, n in enumerate(sheets, 1)) + "</sheets></workbook>"
    sst = f'<?xml version="1.0"?><sst {SNS}>' + "".join(f"<si><t>{escape(s)}</t></si>" for s in strings) + "</sst>"
    files = {"xl/workbook.xml": wb, "xl/sharedStrings.xml": sst}
    for i, _ in enumerate(sheets, 1):
        files[f"xl/worksheets/sheet{i}.xml"] = (
            f'<?xml version="1.0"?><worksheet {SNS}><sheetData><row r="1">'
            '<c r="A1" t="s"><v>0</v></c><c r="B1"><v>3</v></c><c r="C1"><f>B1*2</f><v>6</v></c>'
            "</row></sheetData></worksheet>")
    _zip(Path(path), files)


def make_pptx(path, slides=(("Title one",), ("Title two", "Body text"))):
    files = {"ppt/presentation.xml": f'<?xml version="1.0"?><p:presentation {PNS}/>'}
    for i, texts in enumerate(slides, 1):
        runs = "".join(f"<a:p><a:r><a:t>{escape(t)}</a:t></a:r></a:p>" for t in texts)
        files[f"ppt/slides/slide{i}.xml"] = (
            f'<?xml version="1.0"?><p:sld {PNS}><p:cSld><p:spTree><p:sp><p:txBody>{runs}</p:txBody></p:sp>'
            "</p:spTree></p:cSld></p:sld>")
    _zip(Path(path), files)


def make_psd(path, width=64, height=48, layers=3, channels=3, depth=8, mode=3):
    head = b"8BPS" + struct.pack(">H", 1) + bytes(6) + struct.pack(">HIIHH", channels, height, width, depth, mode)
    body = struct.pack(">I", 0) + struct.pack(">I", 0)  # color mode data, image resources
    layer_info = struct.pack(">h", layers)
    body += struct.pack(">I", 4 + len(layer_info)) + struct.pack(">I", len(layer_info)) + layer_info
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_bytes(head + body)


def generate(directory) -> list[Path]:
    d = Path(directory)
    make_docx(d / "plain.docx", ["First paragraph.", "Second paragraph.", "Third paragraph."])
    make_docx(d / "with_table.docx", ["Intro", "Outro"], table=True)
    make_xlsx(d / "book.xlsx", sheets=("Data", "Summary"))
    make_pptx(d / "deck.pptx")
    make_psd(d / "art.psd")
    return sorted(p for p in d.iterdir() if p.is_file())
